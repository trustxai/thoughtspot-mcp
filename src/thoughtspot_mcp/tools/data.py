@mcp.tool(
    name="thoughtspot_search_data",
    annotations=ToolAnnotations(
        title="Search ThoughtSpot Data",
        readOnlyHint=True,
        destructiveHint=False,
        idempotentHint=True,
        openWorldHint=True,
    ),
)
async def thoughtspot_search_data(params: SearchDataInput) -> str:
    """Run a TML search query against a Worksheet, View, Table, or SQL view.

    Requires at least view access to the data source; if RBAC is enabled, also
    requires the "Can download detailed data" privilege.

    When to Use:
        - Ad hoc data exploration without a saved Answer or Liveboard, e.g.
          "[sales] by [store]".
        - Programmatic access to a metric broken down by one or more attributes.

    When NOT to Use:
        - To re-fetch an already-saved Answer, use thoughtspot_get_answer_data
          (avoids re-parsing the search string).
        - To fetch a Liveboard visualization's data, use
          thoughtspot_get_liveboard_data.

    Returns:
        Column names and rows for the query. Markdown renders a table capped
        at 50 rows per call (page further with record_offset); JSON returns
        the same capped rows plus a display_truncated flag.

    Examples:
        Basic usage:
            params = {
                "query_string": "[sales] by [store]",
                "logical_table_identifier": "cd252e5c-b552-49a8-821d-3eadaa049cca",
            }
        With a runtime filter:
            params = {
                "query_string": "[sales] by [item type]",
                "logical_table_identifier": "cd252e5c-...",
                "runtime_filter": {"col1": "item type", "op1": "EQ", "val1": "Bags"},
            }

    Error Handling:
        400 usually means an invalid query_string or logical_table_identifier;
        403 means missing view/download privileges on the data source.
    """
    try:
        client = get_client()
        body: dict[str, Any] = {
            "query_string": params.query_string,
            "logical_table_identifier": params.logical_table_identifier,
            **params.to_body(),
        }
        resp = await client.request("POST", "/searchdata", json_body=body)
        data = resp.json()
        contents: list[dict[str, Any]] = data.get("contents", [])

        if params.response_format == ResponseFormat.JSON:
            shown, truncated = _truncate_for_json(contents)
            return to_json({"contents": shown, "display_truncated": truncated})

        if not contents:
            return "No data returned for this query."

        return "\n".join(_fmt_content(c, heading="Search Results") for c in contents)
    except Exception as exc:
        return handle_api_error(exc)


@mcp.tool(
    name="thoughtspot_get_liveboard_data",
    annotations=ToolAnnotations(
        title="Get ThoughtSpot Liveboard Data",
        readOnlyHint=True,
        destructiveHint=False,
        idempotentHint=True,
        openWorldHint=True,
    ),
)
async def thoughtspot_get_liveboard_data(params: GetLiveboardDataInput) -> str:
    """Get the data behind a Liveboard's visualizations.

    Requires at least view access to the Liveboard; if RBAC is enabled, also
    requires the "Can download detailed data" privilege.

    When to Use:
        - Pull the underlying rows for one or more charts on a Liveboard.
        - Include unsaved changes (sort, legend toggles, drill-downs) via
          transient_content generated by the Visual Embed SDK.

    When NOT to Use:
        - To render the Liveboard visually, use thoughtspot_export_liveboard_report
          (PDF/PNG/CSV/XLSX) instead.
        - To fetch a standalone Answer's data, use thoughtspot_get_answer_data.

    Returns:
        One section per visualization with column names and rows. Markdown
        renders a table per visualization capped at 50 rows per call (page
        further with record_offset); JSON returns the same capped rows plus a
        display_truncated flag.

    Examples:
        All visualizations on a Liveboard:
            params = {"metadata_identifier": "a1b2c3d4-..."}
        Specific visualizations only:
            params = {
                "metadata_identifier": "a1b2c3d4-...",
                "visualization_identifiers": ["viz-guid-1", "viz-guid-2"],
            }

    Error Handling:
        404 means the Liveboard GUID/name was not found; 403 means missing
        view/download privileges.
    """
    try:
        client = get_client()
        body: dict[str, Any] = {
            "metadata_identifier": params.metadata_identifier,
            **params.to_body(),
        }
        if params.visualization_identifiers is not None:
            body["visualization_identifiers"] = params.visualization_identifiers
        if params.transient_content is not None:
            body["transient_content"] = params.transient_content

        resp = await client.request("POST", "/metadata/liveboard/data", json_body=body)
        data = resp.json()
        metadata_name = data.get("metadata_name", params.metadata_identifier)
        metadata_id = data.get("metadata_id", params.metadata_identifier)
        contents: list[dict[str, Any]] = data.get("contents", [])

        if params.response_format == ResponseFormat.JSON:
            shown, truncated = _truncate_for_json(contents)
            return to_json(
                {
                    "metadata_id": metadata_id,
                    "metadata_name": metadata_name,
                    "contents": shown,
                    "display_truncated": truncated,
                }
            )

        if not contents:
            return f"No data returned for Liveboard **{metadata_name}** ({metadata_id})."

        sections = [
            _fmt_content(c, heading=c.get("visualization_name") or c.get("visualization_id") or "Visualization")
            for c in contents
        ]
        return f"# {metadata_name} ({metadata_id})\n\n" + "\n".join(sections)
    except Exception as exc:
        return handle_api_error(exc)


